#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""build.py — Constructor por capas del schema MEL (Efecto Áncash).

Motor: PostgreSQL (Azure Database for PostgreSQL). Dialecto conmutable con
`dialect: postgres|tsql` en cada spec.

Lee specs declarativos (spec/*.yaml) y emite, en orden de capa:
  out/sql/NNN_<capa>.sql   DDL aditivo e idempotente (tabla -> índices -> vistas)
  out/diccionario.csv      diccionario de datos (columna por columna)
  out/coherencia.md        chequeos de integridad + convenciones

Diseño: una capa = un archivo de spec. Agregar un proyecto nuevo = agregar un
spec con su prefijo + `order`. Nada se reescribe a mano.

Uso:  python3 build.py
"""
import csv, glob, hashlib, json, os, re, sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "out")
WRITE = True  # --verify lo desactiva (no escribe nada, solo reporta)

try:
    import yaml
except ImportError:
    sys.exit("Falta PyYAML  ->  pip install pyyaml")

SNAKE = re.compile(r"^[a-z][a-z0-9_]*$")

# Palabras reservadas de PostgreSQL: si una columna/tabla coincide (sin comillas),
# rompe el DDL. El chequeo avisa para forzar un nombre alternativo.
RESERVED = {
    "all", "and", "as", "case", "cast", "check", "column", "constraint", "create",
    "default", "delete", "distinct", "drop", "else", "end", "except", "false", "fetch",
    "foreign", "from", "grant", "group", "having", "in", "insert", "intersect", "into",
    "join", "limit", "not", "null", "offset", "on", "or", "order", "primary",
    "references", "returning", "select", "table", "then", "true", "union", "unique",
    "update", "user", "using", "values", "when", "where", "window", "with",
}

# Schema (namespace PostgreSQL) dedicado del programa. Aísla el MEL del resto
# de bases (bd_intranet, bd_analitica): mismo servidor, nombres separados.
SCHEMA = "efectoancash"


def q(name, dialect):
    """Cualifica un objeto con su schema (namespace)."""
    return "%s.%s" % (SCHEMA, name) if dialect == "postgres" else "dbo.%s" % name


def load_config():
    global SCHEMA
    path = os.path.join(ROOT, "spec", "_config.yaml")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            cfg = yaml.safe_load(fh) or {}
        SCHEMA = cfg.get("schema", SCHEMA)

PG_TYPES = [
    (re.compile(r"^nvarchar\(max\)$", re.I), "text"),
    (re.compile(r"^nvarchar\((\d+)\)$", re.I), r"varchar(\1)"),
    (re.compile(r"^nvarchar$", re.I), "text"),
    (re.compile(r"^datetime2$", re.I), "timestamptz"),
    (re.compile(r"^tinyint$", re.I), "smallint"),
    (re.compile(r"^bit$", re.I), "boolean"),
    (re.compile(r"^time\(0\)$", re.I), "time"),
    (re.compile(r"^decimal\(", re.I), "numeric("),
]

PG_DEFAULTS = {
    "sysutcdatetime()": "now()",
    "getutcdate()": "now()",
    "1": "true",
    "0": "false",
}


def pg_type(t):
    for rx, rep in PG_TYPES:
        if rx.match(t):
            return rx.sub(rep, t)
    return t


def pg_default(d):
    s = str(d).strip()
    bare = s.strip("'").lower()
    if "sysutcdatetime" in bare or "getutcdate" in bare:
        return "now()"
    return s


def translate(expr, dialect):
    return expr


def load_specs():
    specs = []
    for path in sorted(glob.glob(os.path.join(ROOT, "spec", "*.yaml"))):
        if os.path.basename(path).startswith("_"):
            continue
        with open(path, encoding="utf-8") as fh:
            s = yaml.safe_load(fh) or {}
        s["_file"] = os.path.basename(path)
        specs.append(s)
    specs.sort(key=lambda s: (s.get("order", 999), s.get("layer", "")))
    return specs


def index_tables(specs):
    tables = {}
    for s in specs:
        for tb in (s.get("tables") or []):
            tables[tb["name"]] = tb
    return tables


def col_line(c, dialect):
    name, typ = c["name"], c["type"]
    if dialect == "postgres":
        typ = pg_type(typ)
    parts = [name, typ]
    if c.get("identity"):
        parts.append("generated by default as identity" if dialect == "postgres"
                     else "IDENTITY(1,1)")
    if c.get("notnull"):
        parts.append("NOT NULL")
    if c.get("pk"):
        parts.append("PRIMARY KEY")
    elif c.get("unique"):
        parts.append("UNIQUE")
    if c.get("default") is not None:
        if dialect == "postgres":
            d = pg_default(c["default"])
            if typ == "boolean" and d in ("1", "0"):
                d = "true" if d == "1" else "false"
        else:
            d = str(c["default"])
        parts.append("DEFAULT " + d)
    if c.get("fk") and dialect != "postgres":
        dest, _, dcol = c["fk"].partition(".")
        parts.append("REFERENCES %s(%s)" % (q(dest, dialect), dcol or "id"))
    return "  " + " ".join(parts)


def emit_table(tb, dialect):
    tname = q(tb["name"], dialect)
    if dialect == "postgres":
        head = "CREATE TABLE IF NOT EXISTS %s (" % tname
    else:
        head = "IF OBJECT_ID(N'%s', N'U') IS NULL\nBEGIN\n  CREATE TABLE %s (" % (tname, tname)
    cols = [col_line(c, dialect) for c in (tb.get("columns") or [])]
    body = ",\n".join(cols)
    if dialect == "postgres":
        return head + "\n" + body + "\n);"
    return head + "\n" + body + "\n  );\nEND;"


def emit_indexes(tb, dialect):
    out = []
    for ix in (tb.get("indexes") or []):
        uq = "UNIQUE " if ix.get("unique") else ""
        cols = ", ".join(ix["cols"])
        if dialect == "postgres":
            # Nota: en PostgreSQL el nombre del índice NO admite qualificar con
            # schema (hereda el de la tabla). Usar nombre simple.
            out.append("CREATE %sINDEX IF NOT EXISTS %s ON %s (%s);"
                       % (uq, ix["name"], q(tb["name"], dialect), cols))
        else:
            out.append("IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='%s')\n"
                       "  CREATE %sINDEX %s ON %s (%s);"
                       % (ix["name"], uq, ix["name"], q(tb["name"], dialect), cols))
    return "\n".join(out)


def esc(s):
    return str(s).replace("'", "''")


def emit_comments(tb, dialect):
    """Auto-documentación: COMMENT ON tabla/columna (solo PostgreSQL). Idempotente."""
    if dialect != "postgres":
        return ""
    out = []
    if tb.get("nota"):
        out.append("COMMENT ON TABLE %s IS '%s';" % (q(tb["name"], dialect), esc(tb["nota"])))
    for c in (tb.get("columns") or []):
        if c.get("note"):
            out.append("COMMENT ON COLUMN %s.%s IS '%s';"
                       % (q(tb["name"], dialect), c["name"], esc(c["note"])))
    return "\n".join(out)


def emit_views(spec, dialect):
    out = []
    for vw in (spec.get("views") or []):
        if dialect == "postgres":
            out.append("CREATE OR REPLACE VIEW %s AS\n%s;" % (q(vw["name"], dialect), vw["sql"].strip()))
        else:
            out.append("CREATE OR ALTER VIEW %s AS\n%s\nGO" % (q(vw["name"], dialect), vw["sql"].strip()))
    return "\n".join(out)


def build_sql(specs):
    if not WRITE:
        return specs
    os.makedirs(os.path.join(OUT, "sql"), exist_ok=True)
    for s in specs:
        d = s.get("dialect", "postgres")
        blocks = ["/* %s  —  capa %s  (%s)\n   %s\n   Schema: %s · Motor: %s · generado por build.py — no editar a mano. */"
                  % (s.get("_file"), s.get("layer"), s.get("proyecto", "-"),
                     " ".join((s.get("descripcion") or "").split()), SCHEMA, d)]
        if d == "postgres":
            blocks.append("CREATE SCHEMA IF NOT EXISTS %s;\nSET search_path TO %s, public;" % (SCHEMA, SCHEMA))
        for tb in (s.get("tables") or []):
            blocks.append("/* -- %s -- %s */" % (tb["name"], " ".join((tb.get("nota") or "").split())))
            blocks.append(emit_table(tb, d))
            idx = emit_indexes(tb, d)
            if idx:
                blocks.append(idx)
            cm = emit_comments(tb, d)
            if cm:
                blocks.append(cm)
        for ix in (s.get("indexes") or []):
            blocks.append(emit_indexes({"name": ix["table"], "indexes": [ix]}, d))
        blocks.append(emit_views(s, d))
        fname = "%03d_%s.sql" % (s.get("order", 999), s.get("layer"))
        with open(os.path.join(OUT, "sql", fname), "w", encoding="utf-8") as fh:
            fh.write("\n\n".join(b for b in blocks if b.strip()) + "\n")
    # FKs al final (cuando TODAS las tablas ya existen) -> sin problemas de orden.
    cons = []
    for s in specs:
        if s.get("dialect", "postgres") != "postgres":
            continue
        for tb in (s.get("tables") or []):
            for c in (tb.get("columns") or []):
                fk = c.get("fk")
                if not fk:
                    continue
                dest, _, dcol = fk.partition(".")
                cname = "fk_%s_%s" % (tb["name"], c["name"])
                cons.append(
                    "DO $$ BEGIN\n  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '%s') THEN\n"
                    "    ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s(%s);\n"
                    "  END IF;\nEND $$;"
                    % (cname, q(tb["name"], "postgres"), cname, c["name"],
                       q(dest, "postgres"), dcol or "id"))
    if cons:
        with open(os.path.join(OUT, "sql", "999_fk.sql"), "w", encoding="utf-8") as fh:
            fh.write("/* 999_fk  —  integridad referencial (emitida al final, idempotente). */\n\n"
                     + "\n\n".join(cons) + "\n")
    return specs


def build_diccionario(specs):
    rows = []
    for s in specs:
        for tb in (s.get("tables") or []):
            for c in (tb.get("columns") or []):
                rows.append({
                    "esquema": SCHEMA, "capa": s.get("layer"), "tabla": tb["name"], "columna": c["name"],
                    "tipo": c["type"], "pk": "S" if c.get("pk") else "",
                    "fk": c.get("fk", ""), "notnull": "S" if c.get("notnull") else "",
                    "nota": c.get("note", ""),
                })
    os.makedirs(OUT, exist_ok=True)
    if not WRITE:
        return rows
    with open(os.path.join(OUT, "diccionario.csv"), "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["esquema", "capa", "tabla", "columna", "tipo", "pk", "fk", "notnull", "nota"])
        w.writeheader()
        w.writerows(rows)
    return rows


def coherencia(specs, tables):
    warn, ok = [], []
    prefixes = {s.get("layer"): s.get("prefix", "") for s in specs}
    for name, tb in tables.items():
        for c in (tb.get("columns") or []):
            fk = c.get("fk")
            if not fk:
                continue
            dest, _, dcol = fk.partition(".")
            if dest not in tables:
                warn.append("FK huérfana: %s.%s -> %s (tabla destino no existe)" % (name, c["name"], fk))
            elif dcol and dcol not in [x["name"] for x in tables[dest].get("columns", [])]:
                warn.append("FK a columna inexistente: %s.%s -> %s" % (name, c["name"], fk))
    for name, tb in tables.items():
        pks = [c["name"] for c in (tb.get("columns") or []) if c.get("pk")]
        if len(pks) == 0:
            warn.append("Sin PK: %s" % name)
        elif len(pks) > 1:
            warn.append("PK múltiple (%s): %s" % (",".join(pks), name))
    for name, tb in tables.items():
        if not SNAKE.match(name):
            warn.append("Nombre fuera de snake_case: %s" % name)
        if not any(px and name.startswith(px) for px in prefixes.values()):
            warn.append("Sin prefijo de capa conocido: %s" % name)
        if name.lower() in RESERVED:
            warn.append("Nombre reservado (tabla): %s" % name)
        for c in (tb.get("columns") or []):
            if c["name"].lower() in RESERVED:
                warn.append("Columna con palabra reservada de PostgreSQL: %s.%s" % (name, c["name"]))
    # Índices: nombres duplicados o demasiado largos (PostgreSQL limita a 63 bytes)
    seen = {}
    for name, tb in tables.items():
        for ix in (tb.get("indexes") or []):
            seen.setdefault(ix["name"], []).append(name)
    for s2 in specs:
        for ix in (s2.get("indexes") or []):
            seen.setdefault(ix["name"], []).append(ix["table"])
    for n, owners in seen.items():
        if len(owners) > 1:
            warn.append("Índice duplicado: %s (%s)" % (n, ", ".join(owners)))
        if len(n) > 63:
            warn.append("Índice con nombre > 63 caracteres: %s" % n)
    if not warn:
        ok.append("Sin hallazgos: FKs, PKs y nombres coherentes.")
    lines = ["# Coherencia del modelo — Efecto Áncash MEL", "",
             "Generado por `build.py` (PostgreSQL). Capas y tablas:", ""]
    for s in specs:
        n = len(s.get("tables") or [])
        lines.append("- **%s** (`order %s`, prefijo `%s`): %d tablas — %s"
                     % (s.get("layer"), s.get("order"), s.get("prefix", ""), n,
                        " ".join((s.get("descripcion") or "").split())[:90]))
    lines += ["", "## Chequeos", ""]
    if warn:
        lines.append("**%d avisos:**" % len(warn))
        lines += ["- ⚠️ " + w for w in warn]
    for o in ok:
        lines.append("- ✅ " + o)
    os.makedirs(OUT, exist_ok=True)
    if not WRITE:
        return warn
    with open(os.path.join(OUT, "coherencia.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return warn


def write_manifest(specs, tables, rows):
    """Manifiesto firmado (hash por archivo) para detectar cambios y aplicar con seguridad."""
    if not WRITE:
        return
    files = {}
    for f in sorted(glob.glob(os.path.join(OUT, "sql", "*.sql"))):
        files[os.path.basename(f)] = hashlib.sha256(open(f, "rb").read()).hexdigest()[:16]
    m = {
        "schema": SCHEMA,
        "generado_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "capas": len(specs),
        "tablas": len(tables),
        "columnas": len(rows),
        "archivos": files,
    }
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "manifiesto.json"), "w", encoding="utf-8") as fh:
        json.dump(m, fh, indent=2, ensure_ascii=False)
    return m


def main():
    global WRITE
    if "--verify" in sys.argv or "--dry" in sys.argv:
        WRITE = False
    load_config()
    specs = load_specs()
    if not specs:
        sys.exit("No hay specs en spec/*.yaml")
    tables = index_tables(specs)
    build_sql(specs)
    rows = build_diccionario(specs)
    warn = coherencia(specs, tables)
    write_manifest(specs, tables, rows)
    print("OK%s · schema %s · %d capas · %d tablas · %d columnas"
          % (" (verify)" if not WRITE else "", SCHEMA, len(specs), len(tables), len(rows)))
    for s in specs:
        print("   %03d  %-16s %2d tablas  (%s)" % (s.get("order", 999), s.get("layer"),
                                                   len(s.get("tables") or []), s["_file"]))
    print("   avisos de coherencia: %d" % len(warn))
    for w in warn[:20]:
        print("     -", w)
    print("   ->", OUT)


if __name__ == "__main__":
    main()
