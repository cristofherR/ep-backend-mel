  id int generated by default as identity PRIMARY KEY,
  core_ie_id int NOT NULL UNIQUE,
  anexo varchar(10),
  cod_local varchar(20),
  forma varchar(40),
  area_censo varchar(6),
  des_area_censo varchar(20),
  gestion varchar(6),
  tipo_gestion varchar(60),
  ges_dep varchar(10),
  des_ges_dep varchar(60),
  director varchar(160),
  telefono varchar(30),
  email varchar(160),
  pagweb varchar(200),
  direccion varchar(240),
  localidad varchar(160),
  codcp_inei varchar(20),
  cod_ccpp varchar(20),
  cod_geo varchar(20),
  departamento varchar(60),
  region varchar(60),
  cod_ooii varchar(20),
  dreugel varchar(120),
  tipo_programa varchar(60),
  cod_turno varchar(6),
  turno varchar(30),
  nro_ruc varchar(20),
  razon_social varchar(200),
  promotor varchar(200),
  estado varchar(6),
  des_estado varchar(30),
  fecha_registro date,
  fecha_actualiza date,
  zona_frontera varchar(20),
  pais_colindante varchar(30),
  vraem varchar(20),
  inte_vraem varchar(20),
  matricula_total int,
  matricula_hombres int,
  matricula_mujeres int,
  n_docentes int,
  n_secciones int,
  cod_caracteristica varchar(10),
  des_caracteristica varchar(60),
  es_efecto_ancash boolean DEFAULT false
);

COMMENT ON TABLE efectoancash.pad_escuela IS 'Detalle ESCALE por IE x Nivel (1:1 con core_ie). Clave natural = core_ie.cod_mod.';
COMMENT ON COLUMN efectoancash.pad_escuela.forma IS 'Escolarizada/No escolarizada';
COMMENT ON COLUMN efectoancash.pad_escuela.des_area_censo IS 'Urbana/Rural';
COMMENT ON COLUMN efectoancash.pad_escuela.tipo_gestion IS 'Pública de gestión directa...';
COMMENT ON COLUMN efectoancash.pad_escuela.dreugel IS 'D_DREUGEL';
COMMENT ON COLUMN efectoancash.pad_escuela.des_estado IS 'Activo';
COMMENT ON COLUMN efectoancash.pad_escuela.matricula_total IS 'TALUM';
COMMENT ON COLUMN efectoancash.pad_escuela.matricula_hombres IS 'TALUM_HOM';
COMMENT ON COLUMN efectoancash.pad_escuela.matricula_mujeres IS 'TALUM_MUJ';
COMMENT ON COLUMN efectoancash.pad_escuela.n_docentes IS 'TDOC';
COMMENT ON COLUMN efectoancash.pad_escuela.n_secciones IS 'TSEC';
COMMENT ON COLUMN efectoancash.pad_escuela.des_caracteristica IS 'Polidocente Completo...';
COMMENT ON COLUMN efectoancash.pad_escuela.es_efecto_ancash IS 'col EA (Sí/blank)';

/* -- pad_escuela_componente -- Membresía IE x componente (cols PDL/QM/PDLD/LECTO/CCA/MS/ACADEMIA/PDLE). */

CREATE TABLE IF NOT EXISTS efectoancash.pad_escuela_componente (
  id int generated by default as identity PRIMARY KEY,
  core_ie_id int NOT NULL,
  componente_id int NOT NULL,
  marca varchar(10),
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.pad_escuela_componente IS 'Membresía IE x componente (cols PDL/QM/PDLD/LECTO/CCA/MS/ACADEMIA/PDLE).';
COMMENT ON COLUMN efectoancash.pad_escuela_componente.marca IS 'valor de la col (1, 2, 3...)';

CREATE INDEX IF NOT EXISTS ix_pad_escuela_dreugel ON efectoancash.pad_escuela (dreugel, des_area_censo);

CREATE UNIQUE INDEX IF NOT EXISTS ix_pad_comp ON efectoancash.pad_escuela_componente (core_ie_id, componente_id);

CREATE OR REPLACE VIEW efectoancash.vw_ie_componente AS
SELECT ec.core_ie_id, c.codigo AS componente, c.nombre AS componente_nombre, ec.marca
FROM pad_escuela_componente ec
JOIN core_componente c ON c.id = ec.componente_id;
CREATE OR REPLACE VIEW efectoancash.vw_ie_intervencion AS
SELECT ie.id AS core_ie_id, ie.cod_mod, ie.cod_unico, ie.nombre, ie.nivel, ie.ugt_id,
       ec.componente, ec.marca
FROM core_ie ie
JOIN vw_ie_componente ec ON ec.core_ie_id = ie.id;
