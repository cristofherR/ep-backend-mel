   Capa 5 — ESQUELETO Academia Juvenil (componente PROG-8). Ya existe trabajo previo (Power BI + Deneb: radar de habilidades + cartilla por estudiante). El radar se modela como habilidades + evaluaciones por corte; la cartilla como snapshot.
   Schema: efectoancash · Motor: postgres · generado por build.py — no editar a mano. */

CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- aj_habilidad -- Dimensión del radar de habilidades (eje). */

CREATE TABLE IF NOT EXISTS efectoancash.aj_habilidad (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE,
  nombre varchar(120) NOT NULL,
  orden smallint
);

COMMENT ON TABLE efectoancash.aj_habilidad IS 'Dimensión del radar de habilidades (eje).';

/* -- aj_participante -- Estudiante de la Academia Juvenil. */

CREATE TABLE IF NOT EXISTS efectoancash.aj_participante (
  id int generated by default as identity PRIMARY KEY,
  ie_id int,
  persona_id int,
  cohorte varchar(20),
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.aj_participante IS 'Estudiante de la Academia Juvenil.';

/* -- aj_evaluacion_habilidad -- Valor por participante x habilidad x corte (alimenta el radar). */

CREATE TABLE IF NOT EXISTS efectoancash.aj_evaluacion_habilidad (
  id bigint generated by default as identity PRIMARY KEY,
  participante_id int NOT NULL,
  habilidad_id int NOT NULL,
  corte_id int,
  valor numeric(6,2)
);

COMMENT ON TABLE efectoancash.aj_evaluacion_habilidad IS 'Valor por participante x habilidad x corte (alimenta el radar).';

/* -- aj_cartilla -- Cartilla (snapshot) por participante; semáforo HSE y fuente centro poblado por confirmar. */

CREATE TABLE IF NOT EXISTS efectoancash.aj_cartilla (
  id int generated by default as identity PRIMARY KEY,
  participante_id int NOT NULL,
  periodo_id int,
  semaforo_id int,
  url varchar(500)
);

COMMENT ON TABLE efectoancash.aj_cartilla IS 'Cartilla (snapshot) por participante; semáforo HSE y fuente centro poblado por confirmar.';

CREATE INDEX IF NOT EXISTS ix_aj_eval_part ON efectoancash.aj_evaluacion_habilidad (participante_id, habilidad_id);
