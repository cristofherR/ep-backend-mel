/* 15_instrumentos.yaml  —  capa instrumentos  (_transversal)
   Capa 1b — Motor de instrumentos (encuestas y evaluaciones). Evita crear 30 tablas de preguntas por proyecto: CCA (Docentes 30+4, Familias 24+2), MS (Docentes 24+3, Familias 23+3, Estudiantes) y satisfacción (Item_1..5) se modelan como definición de ítems + respuestas. Agregar un cuestionario nuevo = filas, no columnas.
   Schema: efectoancash · Motor: postgres · generado por build.py — no editar a mano. */

CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- inst_instrumento -- Definición de un cuestionario/evaluación. */

CREATE TABLE IF NOT EXISTS efectoancash.inst_instrumento (
  id int generated by default as identity PRIMARY KEY,
  proyecto_id int,
  codigo varchar(40) NOT NULL UNIQUE,
  nombre varchar(160) NOT NULL,
  publico varchar(20),
  n_preguntas smallint
);

COMMENT ON TABLE efectoancash.inst_instrumento IS 'Definición de un cuestionario/evaluación.';
COMMENT ON COLUMN efectoancash.inst_instrumento.codigo IS 'CCA_DOCENTES, MS_FAMILIAS, SATISFACCION...';
COMMENT ON COLUMN efectoancash.inst_instrumento.publico IS 'docentes/familias/estudiantes/asistentes';

/* -- inst_item -- Ítem/pregunta del instrumento (Preg_1..N + abiertas). */

CREATE TABLE IF NOT EXISTS efectoancash.inst_item (
  id int generated by default as identity PRIMARY KEY,
  instrumento_id int NOT NULL,
  bloque varchar(60),
  orden smallint NOT NULL,
  codigo varchar(20),
  texto varchar(400),
  tipo_respuesta varchar(20)
);

COMMENT ON TABLE efectoancash.inst_item IS 'Ítem/pregunta del instrumento (Preg_1..N + abiertas).';
COMMENT ON COLUMN efectoancash.inst_item.bloque IS 'Bloq_1..5 en MS';
COMMENT ON COLUMN efectoancash.inst_item.codigo IS 'Preg_1, Pregunta_abierta_1';
COMMENT ON COLUMN efectoancash.inst_item.tipo_respuesta IS 'escala/opcion/abierta/indicador';

/* -- inst_intento -- Aplicación de un instrumento (un respondente, una IE, un corte Pre/Post). */

CREATE TABLE IF NOT EXISTS efectoancash.inst_intento (
  id int generated by default as identity PRIMARY KEY,
  instrumento_id int NOT NULL,
  ie_id int,
  persona_id int,
  corte_id int,
  fecha_aplicacion date,
  facilitador_id int
);

COMMENT ON TABLE efectoancash.inst_intento IS 'Aplicación de un instrumento (un respondente, una IE, un corte Pre/Post).';
COMMENT ON COLUMN efectoancash.inst_intento.persona_id IS 'respondente (o NULL si es roster)';
COMMENT ON COLUMN efectoancash.inst_intento.corte_id IS 'Pre test / Post test';

/* -- inst_respuesta -- Respuesta a un ítem (EAV tipado). Soporta escalas y abiertas. */

CREATE TABLE IF NOT EXISTS efectoancash.inst_respuesta (
  id bigint generated by default as identity PRIMARY KEY,
  intento_id int NOT NULL,
  item_id int NOT NULL,
  valor_texto varchar(600),
  valor_num numeric(6,2)
);

COMMENT ON TABLE efectoancash.inst_respuesta IS 'Respuesta a un ítem (EAV tipado). Soporta escalas y abiertas.';

CREATE INDEX IF NOT EXISTS ix_inst_respuesta_intento ON efectoancash.inst_respuesta (intento_id, item_id);

CREATE INDEX IF NOT EXISTS ix_inst_item_instrumento ON efectoancash.inst_item (instrumento_id, orden);
