   Capa 2 — Módulo CCA (Crecemos con Amor, primera infancia). Migra las 11 pestañas del Sheet actual a tablas normalizadas. Encuestas (Familias/Docentes) viven en la capa `instrumentos`; aquí queda la operación: roster, sesión, asistencia, seguimiento.
   Schema: efectoancash · Motor: postgres · generado por build.py — no editar a mano. */

CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- cca_roster -- Lista de personas por IE, reutilizada entre sesiones de esa IE. */

CREATE TABLE IF NOT EXISTS efectoancash.cca_roster (
  id int generated by default as identity PRIMARY KEY,
  ie_id int NOT NULL,
  persona_id int,
  apellidos varchar(120),
  nombres varchar(120),
  dni varchar(12),
  parentesco_id int,
  estudiante_relacionado varchar(160),
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.cca_roster IS 'Lista de personas por IE, reutilizada entre sesiones de esa IE.';
COMMENT ON COLUMN efectoancash.cca_roster.persona_id IS 'NULL hasta consolidar persona por DNI';
COMMENT ON COLUMN efectoancash.cca_roster.estudiante_relacionado IS 'texto libre (nombre del hijo/a)';

/* -- cca_sesion -- Sesión ejecutada de familias (Reporte al día). Sustituye Cod_mirror/Mirror. */

CREATE TABLE IF NOT EXISTS efectoancash.cca_sesion (
  id int generated by default as identity PRIMARY KEY,
  core_sesion_id int,
  ie_id int NOT NULL,
  etapa_id int,
  ciclo smallint,
  tema varchar(200),
  publico_id int,
  asist_familias int DEFAULT 0,
  asist_docentes int DEFAULT 0,
  asist_otros_cant int DEFAULT 0,
  asist_otros_texto varchar(120),
  desarrollo text,
  incidencia_sn boolean DEFAULT false,
  descripcion_incidencia text,
  atencion_adicional text
);

COMMENT ON TABLE efectoancash.cca_sesion IS 'Sesión ejecutada de familias (Reporte al día). Sustituye Cod_mirror/Mirror.';

/* -- cca_asistencia -- Asistencia persona x sesión + encuesta de satisfacción por asistente. */

CREATE TABLE IF NOT EXISTS efectoancash.cca_asistencia (
  id bigint generated by default as identity PRIMARY KEY,
  cca_sesion_id int NOT NULL,
  roster_id int NOT NULL,
  asistio boolean DEFAULT false,
  intento_satisfaccion_id int
);

COMMENT ON TABLE efectoancash.cca_asistencia IS 'Asistencia persona x sesión + encuesta de satisfacción por asistente.';
COMMENT ON COLUMN efectoancash.cca_asistencia.intento_satisfaccion_id IS 'Item_1..5 + Sugerencias (ítems de SATISFACCION)';

/* -- cca_seguimiento_ie -- Hitos por IE (normaliza la pestaña Seguimiento ancha). */

CREATE TABLE IF NOT EXISTS efectoancash.cca_seguimiento_ie (
  id int generated by default as identity PRIMARY KEY,
  ie_id int NOT NULL,
  hito_id int,
  estado_id int,
  fecha date,
  responsable_id int
);

COMMENT ON TABLE efectoancash.cca_seguimiento_ie IS 'Hitos por IE (normaliza la pestaña Seguimiento ancha).';

CREATE INDEX IF NOT EXISTS ix_cca_asist_sesion ON efectoancash.cca_asistencia (cca_sesion_id);

CREATE INDEX IF NOT EXISTS ix_cca_roster_ie ON efectoancash.cca_roster (ie_id, activo);
