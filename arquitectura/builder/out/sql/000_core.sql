/* -- core_migracion -- Bitácora de migraciones aplicadas (versión + hash del archivo SQL). Permite saber qué está aplicado sin adivinar y crecer con seguridad. */

CREATE TABLE IF NOT EXISTS efectoancash.core_migracion (
  id int generated by default as identity PRIMARY KEY,
  version varchar(20) NOT NULL,
  archivo varchar(120) NOT NULL,
  hash varchar(64),
  aplicado_en timestamptz DEFAULT now(),
  nota varchar(300)
);

COMMENT ON TABLE efectoancash.core_migracion IS 'Bitácora de migraciones aplicadas (versión + hash del archivo SQL). Permite saber qué está aplicado sin adivinar y crecer con seguridad.';
COMMENT ON COLUMN efectoancash.core_migracion.version IS 'NNN de la capa o del seed';
COMMENT ON COLUMN efectoancash.core_migracion.hash IS 'sha256 (16) del archivo aplicado';

CREATE UNIQUE INDEX IF NOT EXISTS ux_core_migracion_archivo_hash ON efectoancash.core_migracion (archivo, hash);

CREATE INDEX IF NOT EXISTS ix_core_ie_ugt ON efectoancash.core_ie (ugt_id, cod_unico);

