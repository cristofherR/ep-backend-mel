/* 00_core.yaml  —  capa core  (_transversal)
   Capa 0 — Núcleo transversal. Dimensiones y entidades compartidas por TODOS los proyectos (programación, CCA, Mente Sana, PDLE, Academia Juvenil). Nada aquí es específico de un proyecto. Es la base del "builder": crece solo. La entidad institucional (IE × Nivel) vive en `core_ie` (fuente: padrón ESCALE, capa `padron`).
   Schema: efectoancash · Motor: postgres · generado por build.py — no editar a mano. */

CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- core_proyecto -- Iniciativas del programa (Efecto Áncash). `tipo` distingue PROGRAMA (nacional, secuencia anual, con participantes/núcleos) de PROYECTO (puntual, facilitadores/sesiones). */

CREATE TABLE IF NOT EXISTS efectoancash.core_proyecto (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(20) NOT NULL UNIQUE,
  nombre varchar(120) NOT NULL,
  tipo varchar(12) DEFAULT 'proyecto',
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.core_proyecto IS 'Iniciativas del programa (Efecto Áncash). `tipo` distingue PROGRAMA (nacional, secuencia anual, con participantes/núcleos) de PROYECTO (puntual, facilitadores/sesiones).';
COMMENT ON COLUMN efectoancash.core_proyecto.codigo IS 'EA, CCA, MS, PDLE, AJ | PDL, QM, PDLD, LECTO';
COMMENT ON COLUMN efectoancash.core_proyecto.tipo IS 'programa | proyecto';

/* -- core_componente -- Catálogo PROG-0..9 / ECO-x con color oficial (fuente Power Apps). */

CREATE TABLE IF NOT EXISTS efectoancash.core_componente (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(10) NOT NULL UNIQUE,
  nombre varchar(120) NOT NULL,
  color_hex char(7),
  proyecto_id int,
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.core_componente IS 'Catálogo PROG-0..9 / ECO-x con color oficial (fuente Power Apps).';
COMMENT ON COLUMN efectoancash.core_componente.codigo IS 'PROG-5, ECO-2...';
COMMENT ON COLUMN efectoancash.core_componente.color_hex IS '#ad1457';
COMMENT ON COLUMN efectoancash.core_componente.proyecto_id IS 'componente dueño (CCA/MS/PDLE/AJ) o NULL si transversal';

/* -- core_ugt -- Unidad de Gestión Territorial (con color oficial). 5 UGT en el padrón. */

CREATE TABLE IF NOT EXISTS efectoancash.core_ugt (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(20) NOT NULL UNIQUE,
  nombre varchar(80) NOT NULL,
  color_hex char(7)
);

COMMENT ON TABLE efectoancash.core_ugt IS 'Unidad de Gestión Territorial (con color oficial). 5 UGT en el padrón.';

/* -- core_ct -- Coordinador Territorial. UGT Mina tiene 2 CT (CT1 = cuenca; CT2 = Huaripampa + Carhuayoc) -> CT es entidad propia, no columna. El CT define el filtro de territorio. */

CREATE TABLE IF NOT EXISTS efectoancash.core_ct (
  id int generated by default as identity PRIMARY KEY,
  persona_id int,
  nombre varchar(120),
  ugt_id int,
  alcance_macro boolean DEFAULT false
);

COMMENT ON TABLE efectoancash.core_ct IS 'Coordinador Territorial. UGT Mina tiene 2 CT (CT1 = cuenca; CT2 = Huaripampa + Carhuayoc) -> CT es entidad propia, no columna. El CT define el filtro de territorio.';
COMMENT ON COLUMN efectoancash.core_ct.nombre IS 'etiqueta de alcance: ''UGT Mina (cuenca)'' / ''UGT Mina (Huaripampa + Carhuayoc)''';
COMMENT ON COLUMN efectoancash.core_ct.ugt_id IS 'NULL si es de alcance macro';

/* -- core_centro_poblado -- Centro poblado. Pertenece a una UGT y a un CT (define el alcance del CT; p.ej. UGT Mina con 2 CT, cuenca vs Huaripampa + Carhuayoc). */

CREATE TABLE IF NOT EXISTS efectoancash.core_centro_poblado (
  id int generated by default as identity PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  alias varchar(120),
  distrito varchar(120),
  provincia varchar(120),
  ugt_id int,
  ct_id int,
  codigo varchar(20) UNIQUE
);

COMMENT ON TABLE efectoancash.core_centro_poblado IS 'Centro poblado. Pertenece a una UGT y a un CT (define el alcance del CT; p.ej. UGT Mina con 2 CT, cuenca vs Huaripampa + Carhuayoc).';
COMMENT ON COLUMN efectoancash.core_centro_poblado.alias IS 'variantes (p.ej. ''CENTRO'' / ''CENTRAL'')';
COMMENT ON COLUMN efectoancash.core_centro_poblado.ct_id IS 'CT responsable (filtro por CT)';

/* -- core_persona -- Persona no-usuario (docente, familia, estudiante, facilitador). DNI natural + surrogate. */

CREATE TABLE IF NOT EXISTS efectoancash.core_persona (
  id int generated by default as identity PRIMARY KEY,
  dni varchar(12) UNIQUE,
  apellidos varchar(120),
  nombres varchar(120),
  telefono varchar(20)
);

COMMENT ON TABLE efectoancash.core_persona IS 'Persona no-usuario (docente, familia, estudiante, facilitador). DNI natural + surrogate.';

/* -- core_rol -- Roles de acceso (Admin MEL, CT, Facilitador, Jefe/Comunicaciones/Formación macro). */

CREATE TABLE IF NOT EXISTS efectoancash.core_rol (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE,
  nombre varchar(80) NOT NULL,
  es_macro boolean DEFAULT false
);

COMMENT ON TABLE efectoancash.core_rol IS 'Roles de acceso (Admin MEL, CT, Facilitador, Jefe/Comunicaciones/Formación macro).';
COMMENT ON COLUMN efectoancash.core_rol.es_macro IS '1 = no sujeto a territorio (todos los territorios)';

/* -- core_usuario -- Usuario de la app. Credenciales hasheadas; nunca PII expuesta. */

CREATE TABLE IF NOT EXISTS efectoancash.core_usuario (
  id int generated by default as identity PRIMARY KEY,
  persona_id int,
  email varchar(160) NOT NULL UNIQUE,
  hash_clave varchar(128),
  rol_id int,
  ugt_id int,
  push_token varchar(255),
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.core_usuario IS 'Usuario de la app. Credenciales hasheadas; nunca PII expuesta.';
COMMENT ON COLUMN efectoancash.core_usuario.ugt_id IS 'NULL si rol macro';
COMMENT ON COLUMN efectoancash.core_usuario.push_token IS 'token FCM/n8n para push móvil (alertas/incidencias)';

/* -- core_usuario_alcance -- Alcance por usuario (M:N). Un usuario puede cubrir varias UGT (ej. Albert Moro 2 UGT; CT dentro de UGT Mina se distingue por core_ct). Para roles programa/formación el alcance puede depender del programa. Un usuario = un rol; N alcances. */

CREATE TABLE IF NOT EXISTS efectoancash.core_usuario_alcance (
  id int generated by default as identity PRIMARY KEY,
  usuario_id int NOT NULL,
  ugt_id int,
  ct_id int,
  programa_id int,
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.core_usuario_alcance IS 'Alcance por usuario (M:N). Un usuario puede cubrir varias UGT (ej. Albert Moro 2 UGT; CT dentro de UGT Mina se distingue por core_ct). Para roles programa/formación el alcance puede depender del programa. Un usuario = un rol; N alcances.
';
COMMENT ON COLUMN efectoancash.core_usuario_alcance.ct_id IS 'alcance de CT (caso UGT Mina)';
COMMENT ON COLUMN efectoancash.core_usuario_alcance.programa_id IS 'alcance por programa (rol programa/formación)';

/* -- core_ie -- IE x Nivel (entidad canónica). cod_mod = clave natural del padrón ESCALE; cod_unico = COD_Inst+Nivel (clave de MS). El detalle ESCALE completo vive en pad_escuela. */

CREATE TABLE IF NOT EXISTS efectoancash.core_ie (
  id int generated by default as identity PRIMARY KEY,
  cod_mod varchar(20) NOT NULL UNIQUE,
  cod_inst varchar(20) NOT NULL,
  cod_unico varchar(40) UNIQUE,
  nombre varchar(200) NOT NULL,
  niv_mod varchar(6),
  nivel varchar(40),
  ugt_id int,
  provincia varchar(60),
  distrito varchar(60),
  cen_poblado varchar(160),
  lat numeric(9,6),
  lon numeric(9,6)
);

COMMENT ON TABLE efectoancash.core_ie IS 'IE x Nivel (entidad canónica). cod_mod = clave natural del padrón ESCALE; cod_unico = COD_Inst+Nivel (clave de MS). El detalle ESCALE completo vive en pad_escuela.';
COMMENT ON COLUMN efectoancash.core_ie.cod_mod IS 'COD_MOD (padrón ESCALE)';
COMMENT ON COLUMN efectoancash.core_ie.cod_unico IS 'cod_inst || ''-'' || niv_mod';
COMMENT ON COLUMN efectoancash.core_ie.niv_mod IS 'A2 Inicial, B0 Primaria, A5/F0...';

