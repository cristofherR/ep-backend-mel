CREATE UNIQUE INDEX IF NOT EXISTS ix_core_usuario_email ON efectoancash.core_usuario (email);

CREATE OR REPLACE VIEW efectoancash.vw_reportabilidad AS
SELECT p.anio, p.mes, a.ugt_id,
       COUNT(*) AS programadas,
       SUM(CASE WHEN a.fecha_ejecucion IS NOT NULL THEN 1 ELSE 0 END) AS reportadas,
       ROUND(100.0 * SUM(CASE WHEN a.fecha_ejecucion IS NOT NULL THEN 1 ELSE 0 END)
            / NULLIF(COUNT(*),0), 2) AS pct_reportabilidad
FROM core_actividad a
JOIN core_periodo p ON p.id = a.periodo_id
GROUP BY p.anio, p.mes, a.ugt_id;
