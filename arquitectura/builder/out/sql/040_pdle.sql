CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- pdle_programa_sesion -- Sesión de liderazgo estudiantil, ligada a una IE y a una etapa. */

CREATE TABLE IF NOT EXISTS efectoancash.pdle_programa_sesion (
  id int generated by default as identity PRIMARY KEY,
  core_sesion_id int,
  ie_id int NOT NULL,
  etapa_id int,
  tema varchar(200),
  n_participantes int DEFAULT 0
);

COMMENT ON TABLE efectoancash.pdle_programa_sesion IS 'Sesión de liderazgo estudiantil, ligada a una IE y a una etapa.';

/* -- pdle_participante -- Estudiantes/líderes que participan en una sesión. */

CREATE TABLE IF NOT EXISTS efectoancash.pdle_participante (
  id int generated by default as identity PRIMARY KEY,
  pdle_programa_sesion_id int NOT NULL,
  persona_id int,
  rol_liderazgo varchar(80),
  asistio boolean DEFAULT false
);

COMMENT ON TABLE efectoancash.pdle_participante IS 'Estudiantes/líderes que participan en una sesión.';

/* -- pdle_evaluacion -- Resultado por participante/indicador (instrumentos o ítems propios). */

CREATE TABLE IF NOT EXISTS efectoancash.pdle_evaluacion (
  id bigint generated by default as identity PRIMARY KEY,
  participante_id int,
  intento_id int,
  indicador varchar(120),
  valor numeric(6,2)
);

COMMENT ON TABLE efectoancash.pdle_evaluacion IS 'Resultado por participante/indicador (instrumentos o ítems propios).';

CREATE INDEX IF NOT EXISTS ix_pdle_part_sesion ON efectoancash.pdle_participante (pdle_programa_sesion_id);
