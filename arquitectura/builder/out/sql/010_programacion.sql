CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- prog_poa_actividad_grande -- Actividad grande del POA (anual/trimestral; puede repetirse por mes). Es la lista EA_POA. Solo el Admin MEL la crea, edita y actualiza (visibilidad admin); lleva auditoría. `anio` explícito para 2026 (datos actuales) y siguientes (2027+). */

CREATE TABLE IF NOT EXISTS efectoancash.prog_poa_actividad_grande (
  id int generated by default as identity PRIMARY KEY,
  anio smallint NOT NULL,
  componente_id int,
  ugt_id int,
  ct_id int,
  alcance_macro varchar(20),
  periodo_id int,
  nombre varchar(200) NOT NULL,
  meta varchar(200),
  responsable_id int,
  actor_externo varchar(160),
  resultado_real text,
  comentario text,
  estado_id int,
  visibilidad varchar(10) DEFAULT 'admin',
  orden smallint,
  creado_por int,
  creado_en timestamptz DEFAULT now(),
  actualizado_por int,
  actualizado_en timestamptz
);

COMMENT ON TABLE efectoancash.prog_poa_actividad_grande IS 'Actividad grande del POA (anual/trimestral; puede repetirse por mes). Es la lista EA_POA. Solo el Admin MEL la crea, edita y actualiza (visibilidad admin); lleva auditoría. `anio` explícito para 2026 (datos actuales) y siguientes (2027+).
';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.anio IS 'año de la actividad (2026, 2027…) — denormalizado para filtro/partición';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.alcance_macro IS 'alcance ''Region'' (no es UGT ni CT)';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.periodo_id IS 'anio + trimestre + mes programado';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.meta IS 'KR trimestral / resultado esperado';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.actor_externo IS 'UGEL / Programa EA / IIEE focalizadas / Territorio / COPALE…';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.estado_id IS 'catálogo estado_grande (5)';
COMMENT ON COLUMN efectoancash.prog_poa_actividad_grande.visibilidad IS 'solo Admin MEL (ingreso/edición)';

/* -- prog_actividad_pequena -- Actividad pequeña = una por actividad grande. La crean los usuarios. */

CREATE TABLE IF NOT EXISTS efectoancash.prog_actividad_pequena (
  id int generated by default as identity PRIMARY KEY,
  act_grande_id int NOT NULL,
  ie_id int,
  distrito varchar(80),
  centro_poblado varchar(120),
  centro_poblado_id int,
  nivel varchar(20),
  especifico varchar(240),
  responsable_id int,
  fecha_programada timestamptz,
  hora_inicio time,
  estado_id int
);

COMMENT ON TABLE efectoancash.prog_actividad_pequena IS 'Actividad pequeña = una por actividad grande. La crean los usuarios.';
COMMENT ON COLUMN efectoancash.prog_actividad_pequena.centro_poblado_id IS 'catalogado; permite el filtro por CT';
COMMENT ON COLUMN efectoancash.prog_actividad_pequena.estado_id IS 'catálogo estado_pequena';

/* -- prog_reporte -- Reporte de ejecución de una actividad pequeña (Guardar y enviar). */

CREATE TABLE IF NOT EXISTS efectoancash.prog_reporte (
  id int generated by default as identity PRIMARY KEY,
  act_pequena_id int NOT NULL,
  descripcion text,
  logro text,
  n_docentes int DEFAULT 0,
  n_familias int DEFAULT 0,
  n_estudiantes int DEFAULT 0,
  n_otros int DEFAULT 0,
  estado varchar(20) DEFAULT 'Pendiente',
  enviado_en timestamptz
);

COMMENT ON TABLE efectoancash.prog_reporte IS 'Reporte de ejecución de una actividad pequeña (Guardar y enviar).';
COMMENT ON COLUMN efectoancash.prog_reporte.estado IS 'Pendiente/Enviado';

/* -- prog_incidencia -- Incidencia o Alerta reportada (bloque dinámico del reporte). Categoría -> subcategoría. */

CREATE TABLE IF NOT EXISTS efectoancash.prog_incidencia (
  id int generated by default as identity PRIMARY KEY,
  reporte_id int,
  tipo varchar(12) NOT NULL,
  categoria_id int,
  subcategoria_id int,
  nivel_semaforo_id int,
  diagnostico_previo varchar(20),
  descripcion text
);

COMMENT ON TABLE efectoancash.prog_incidencia IS 'Incidencia o Alerta reportada (bloque dinámico del reporte). Categoría -> subcategoría.';
COMMENT ON COLUMN efectoancash.prog_incidencia.tipo IS 'Incidencia/Alerta';
COMMENT ON COLUMN efectoancash.prog_incidencia.nivel_semaforo_id IS 'Informativo..Prioritario';
COMMENT ON COLUMN efectoancash.prog_incidencia.diagnostico_previo IS 'solo rama Alerta NEE';

/* -- prog_indicador_mes -- Snapshot de indicadores de Portada por alcance (CT/UGT/usuario) y mes. */

CREATE TABLE IF NOT EXISTS efectoancash.prog_indicador_mes (
  id int generated by default as identity PRIMARY KEY,
  alcance varchar(20) NOT NULL,
  alcance_id int,
  periodo_id int,
  programadas int DEFAULT 0,
  reportadas int DEFAULT 0
);

COMMENT ON TABLE efectoancash.prog_indicador_mes IS 'Snapshot de indicadores de Portada por alcance (CT/UGT/usuario) y mes.';
COMMENT ON COLUMN efectoancash.prog_indicador_mes.alcance IS 'ugt/ct/usuario';

/* -- prog_alerta_regla -- Regla de enrutamiento de alertas/incidencias (motor n8n). Define qué severidad dispara una notificación y a qué roles. Permite escalado y re-notificación. */

CREATE TABLE IF NOT EXISTS efectoancash.prog_alerta_regla (
  id int generated by default as identity PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  tipo varchar(12),
  nivel_semaforo_min_id int,
  roles_destino varchar(160),
  incluir_jefe boolean DEFAULT true,
  canal varchar(20) DEFAULT 'push',
  escalar_minutos int,
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.prog_alerta_regla IS 'Regla de enrutamiento de alertas/incidencias (motor n8n). Define qué severidad dispara una notificación y a qué roles. Permite escalado y re-notificación.
';
COMMENT ON COLUMN efectoancash.prog_alerta_regla.tipo IS 'Alerta / Incidencia / Ambos';
COMMENT ON COLUMN efectoancash.prog_alerta_regla.nivel_semaforo_min_id IS 'severidad mínima (Informativo..Prioritario)';
COMMENT ON COLUMN efectoancash.prog_alerta_regla.roles_destino IS 'códigos core_rol separados por coma: ct, jefe_territorial, formacion…';
COMMENT ON COLUMN efectoancash.prog_alerta_regla.incluir_jefe IS 'añadir Jefe Territorial del programa';
COMMENT ON COLUMN efectoancash.prog_alerta_regla.canal IS 'push / telegram / whatsapp / email';
COMMENT ON COLUMN efectoancash.prog_alerta_regla.escalar_minutos IS 're-notificar si no se atiende en N min';

/* -- prog_notificacion -- Bandeja de salida (outbox) de notificaciones. Una fila por destinatario; n8n la consume y marca el envío. Fuente del push al CT de la UGT y al Jefe Territorial. */

CREATE TABLE IF NOT EXISTS efectoancash.prog_notificacion (
  id int generated by default as identity PRIMARY KEY,
  incidencia_id int,
  regla_id int,
  destinatario_id int NOT NULL,
  canal varchar(20) DEFAULT 'push',
  asunto varchar(200),
  cuerpo text,
  estado varchar(12) DEFAULT 'pendiente',
  intentos smallint DEFAULT 0,
  enviado_en timestamptz,
  error varchar(400),
  creado_en timestamptz DEFAULT now()
);

COMMENT ON TABLE efectoancash.prog_notificacion IS 'Bandeja de salida (outbox) de notificaciones. Una fila por destinatario; n8n la consume y marca el envío. Fuente del push al CT de la UGT y al Jefe Territorial.
';
COMMENT ON COLUMN efectoancash.prog_notificacion.estado IS 'pendiente / enviado / error';

CREATE INDEX IF NOT EXISTS ix_prog_pequena_grande ON efectoancash.prog_actividad_pequena (act_grande_id, estado_id);

CREATE INDEX IF NOT EXISTS ix_prog_pequena_fecha ON efectoancash.prog_actividad_pequena (fecha_programada);

CREATE INDEX IF NOT EXISTS ix_prog_grande_anio ON efectoancash.prog_poa_actividad_grande (anio, componente_id, ugt_id);

CREATE INDEX IF NOT EXISTS ix_prog_notif_estado ON efectoancash.prog_notificacion (estado, creado_en);

CREATE OR REPLACE VIEW efectoancash.vw_prog_agenda_proxima AS
SELECT pe.id, pe.fecha_programada, ag.nombre AS actividad
FROM prog_actividad_pequena pe
JOIN prog_poa_actividad_grande ag ON ag.id = pe.act_grande_id
WHERE pe.estado_id IS NOT NULL
ORDER BY pe.fecha_programada ASC, ag.nombre ASC
LIMIT 5;;
CREATE OR REPLACE VIEW efectoancash.vw_prog_poa_admin AS
SELECT g.id, g.anio, c.nombre AS componente, u.nombre AS ugt, ct.id AS ct_id,
       g.alcance_macro, p.trimestre, p.mes, g.nombre, g.meta,
       g.actor_externo, g.resultado_real, g.comentario, e.etiqueta AS estado
FROM prog_poa_actividad_grande g
LEFT JOIN core_componente c ON c.id = g.componente_id
LEFT JOIN core_ugt u ON u.id = g.ugt_id
LEFT JOIN core_ct ct ON ct.id = g.ct_id
LEFT JOIN core_periodo p ON p.id = g.periodo_id
LEFT JOIN core_catalogo_item e ON e.id = g.estado_id;;
