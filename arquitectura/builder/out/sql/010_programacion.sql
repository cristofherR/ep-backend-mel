   Capa 1 — Dominio "Gestión de territorio / POA". Migra las listas EA_POA (actividad grande) y EA_Actividades (actividad pequeña) y agrega reporte + incidencia/alerta. NO duplica lo que ya reporta bd_intranet (visitas): core_actividad.tipo permite referenciar el registro de intranet en vez de recapturarlo.
