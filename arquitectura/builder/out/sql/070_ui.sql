/* 70_ui.yaml  —  capa ui  (_transversal)
   Capa 7 — Configuración de interfaz (data-driven UI). Todo lo que en un front suele ir "hardcodeado" (labels, títulos, fuentes, tamaños, orden/fijado de elementos) vive aquí como DATOS, no como código. Permite editar textos, mover o fijar bloques, cambiar tipografía/tamaños y reordenar pantallas SIN recompilar ni re-desplegar. Es el punto de extensión para UI/UX.
   Schema: efectoancash · Motor: postgres · generado por build.py — no editar a mano. */

CREATE SCHEMA IF NOT EXISTS efectoancash;
SET search_path TO efectoancash, public;

/* -- ui_idioma -- Idiomas soportados. Hoy solo 'es'; la estructura ya admite más sin romper textos. */

CREATE TABLE IF NOT EXISTS efectoancash.ui_idioma (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(8) NOT NULL UNIQUE,
  nombre varchar(60) NOT NULL,
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.ui_idioma IS 'Idiomas soportados. Hoy solo ''es''; la estructura ya admite más sin romper textos.';
COMMENT ON COLUMN efectoancash.ui_idioma.codigo IS 'es, en, qu (ISO 639-1)';

/* -- ui_texto -- Diccionario de labels/títulos/tooltips editables por clave. Traduce cada texto de la app sin tocar el código. */

CREATE TABLE IF NOT EXISTS efectoancash.ui_texto (
  id int generated by default as identity PRIMARY KEY,
  clave varchar(120) NOT NULL,
  idioma_id int NOT NULL,
  valor varchar(1000) NOT NULL,
  contexto varchar(60),
  nota varchar(300)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ui_texto_clave_idioma ON efectoancash.ui_texto (clave, idioma_id);

COMMENT ON TABLE efectoancash.ui_texto IS 'Diccionario de labels/títulos/tooltips editables por clave. Traduce cada texto de la app sin tocar el código.';
COMMENT ON COLUMN efectoancash.ui_texto.clave IS 'ej. login.titulo, nav.programacion';
COMMENT ON COLUMN efectoancash.ui_texto.contexto IS 'agrupador: login, nav, cca, ms, indicadores...';

/* -- ui_tema -- Conjuntos de tokens visuales (temas). Uno es el default; se puede cambiar sin tocar el front. */

CREATE TABLE IF NOT EXISTS efectoancash.ui_tema (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(40) NOT NULL UNIQUE,
  nombre varchar(80) NOT NULL,
  es_default boolean DEFAULT false,
  activo boolean DEFAULT true
);

COMMENT ON TABLE efectoancash.ui_tema IS 'Conjuntos de tokens visuales (temas). Uno es el default; se puede cambiar sin tocar el front.';
COMMENT ON COLUMN efectoancash.ui_tema.codigo IS 'base, alto-contraste, oscuro...';

/* -- ui_tema_token -- Tokens de diseño (design tokens): fuentes, tamaños, colores, radios, espacios. Equivale a las variables CSS pero como datos. */

CREATE TABLE IF NOT EXISTS efectoancash.ui_tema_token (
  id int generated by default as identity PRIMARY KEY,
  tema_id int NOT NULL,
  token varchar(60) NOT NULL,
  valor varchar(200) NOT NULL,
  tipo varchar(20),
  grupo varchar(40),
  nota varchar(300)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ui_token_tema ON efectoancash.ui_tema_token (tema_id, token);

COMMENT ON TABLE efectoancash.ui_tema_token IS 'Tokens de diseño (design tokens): fuentes, tamaños, colores, radios, espacios. Equivale a las variables CSS pero como datos.';
COMMENT ON COLUMN efectoancash.ui_tema_token.token IS 'ej. --fuente-base, --fs-lg, --color-primario';
COMMENT ON COLUMN efectoancash.ui_tema_token.tipo IS 'font | size | color | spacing | radius | shadow';
COMMENT ON COLUMN efectoancash.ui_tema_token.grupo IS 'tipografia, color, layout...';

/* -- ui_vista -- Pantallas/rutas de la app PWA. Orden y visibilidad configurables; rol_id define quién la ve. */

CREATE TABLE IF NOT EXISTS efectoancash.ui_vista (
  id int generated by default as identity PRIMARY KEY,
  codigo varchar(40) NOT NULL UNIQUE,
  ruta varchar(120),
  titulo_clave varchar(120),
  icono varchar(60),
  orden int DEFAULT 0,
  activo boolean DEFAULT true,
  rol_id int
);

COMMENT ON TABLE efectoancash.ui_vista IS 'Pantallas/rutas de la app PWA. Orden y visibilidad configurables; rol_id define quién la ve.';
COMMENT ON COLUMN efectoancash.ui_vista.codigo IS 'programacion, cca, mente_sana, indicadores...';
COMMENT ON COLUMN efectoancash.ui_vista.ruta IS 'hash route o path';
COMMENT ON COLUMN efectoancash.ui_vista.titulo_clave IS 'clave en ui_texto (no texto duro)';
COMMENT ON COLUMN efectoancash.ui_vista.rol_id IS 'NULL = todos';

/* -- ui_bloque -- Secciones dentro de una vista. `fijo` = se queda pegado (sticky) al hacer scroll; `orden` = posición. Mover/fijar = editar filas, no HTML. */

CREATE TABLE IF NOT EXISTS efectoancash.ui_bloque (
  id int generated by default as identity PRIMARY KEY,
  vista_id int NOT NULL,
  codigo varchar(60) NOT NULL,
  titulo_clave varchar(120),
  tipo varchar(30),
  orden int DEFAULT 0,
  fijo boolean DEFAULT false,
  visible boolean DEFAULT true,
  ancho varchar(12),
  config text
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ui_bloque_vista_codigo ON efectoancash.ui_bloque (vista_id, codigo);

COMMENT ON TABLE efectoancash.ui_bloque IS 'Secciones dentro de una vista. `fijo` = se queda pegado (sticky) al hacer scroll; `orden` = posición. Mover/fijar = editar filas, no HTML.';
COMMENT ON COLUMN efectoancash.ui_bloque.tipo IS 'kpis | filtros | tabla | grafico | formulario | agenda';
COMMENT ON COLUMN efectoancash.ui_bloque.fijo IS 'sticky';
COMMENT ON COLUMN efectoancash.ui_bloque.ancho IS 'full | half | third';
COMMENT ON COLUMN efectoancash.ui_bloque.config IS 'JSON libre del bloque';

/* -- ui_elemento -- Componente concreto dentro de un bloque (KPI, columna, serie). `fuente_dato` apunta a una vista/consulta del schema; `config` = JSON (colores, umbrales, formato). */

CREATE TABLE IF NOT EXISTS efectoancash.ui_elemento (
  id int generated by default as identity PRIMARY KEY,
  bloque_id int NOT NULL,
  clave varchar(60) NOT NULL,
  tipo varchar(30),
  titulo_clave varchar(120),
  fuente_dato varchar(120),
  orden int DEFAULT 0,
  visible boolean DEFAULT true,
  config text
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ui_elemento_bloque_clave ON efectoancash.ui_elemento (bloque_id, clave);

COMMENT ON TABLE efectoancash.ui_elemento IS 'Componente concreto dentro de un bloque (KPI, columna, serie). `fuente_dato` apunta a una vista/consulta del schema; `config` = JSON (colores, umbrales, formato).';
COMMENT ON COLUMN efectoancash.ui_elemento.tipo IS 'kpi | barra | linea | tabla_col | campo';
COMMENT ON COLUMN efectoancash.ui_elemento.fuente_dato IS 'vista/consulta (ej. vw_resumen_ct)';
COMMENT ON COLUMN efectoancash.ui_elemento.config IS 'JSON: umbrales, formato, colores';

CREATE OR REPLACE VIEW efectoancash.vw_ui_textos AS
SELECT t.clave, t.contexto, t.valor, i.codigo AS idioma
  FROM ui_texto t
  JOIN ui_idioma i ON i.id = t.idioma_id
 WHERE i.activo = true;
CREATE OR REPLACE VIEW efectoancash.vw_ui_tema_activo AS
SELECT tk.token, tk.valor, tk.tipo, tk.grupo, t.codigo AS tema
  FROM ui_tema_token tk
  JOIN ui_tema t ON t.id = tk.tema_id
 WHERE t.activo = true
   AND t.es_default = true;
CREATE OR REPLACE VIEW efectoancash.vw_ui_pantalla AS
SELECT v.codigo AS vista, v.ruta, v.orden AS vista_orden,
       b.codigo AS bloque, b.tipo AS bloque_tipo, b.orden AS bloque_orden,
       b.fijo, b.visible AS bloque_visible, b.ancho,
       e.clave AS elemento, e.tipo AS elemento_tipo, e.orden AS elemento_orden,
       e.fuente_dato, e.visible AS elemento_visible
  FROM ui_vista v
  JOIN ui_bloque b   ON b.vista_id = v.id
  LEFT JOIN ui_elemento e ON e.bloque_id = b.id
 WHERE v.activo = true AND b.visible = true
 ORDER BY v.orden, b.orden, e.orden;
